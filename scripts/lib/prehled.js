const BARVY = {
  fulfilled: "#15803D", partial: "#B45309", in_progress: "#0369A1",
  declared: "#6B7280", not_started: "#6B7280", broken: "#BE123C", stalled: "#BE123C",
};

/* "stalled" je stará hodnota škály z doby před 7/2026. Musí tu být, aby se
   jmenovatel shodoval s App.jsx (score: 1) — a taky proto, že metriky() ji
   níž počítá do „porušeno“, což by bez ní byl kód, který nikdy nenastane. */
const SCORED = new Set(["fulfilled", "partial", "in_progress", "declared", "not_started", "broken", "stalled"]);

function esc(s) {
  return String(s == null ? "" : s)
    .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function datum(iso, lang) {
  if (!iso) return null;
  return new Date(iso).toLocaleDateString(lang === "cs" ? "cs-CZ" : "en-GB",
    { day: "numeric", month: "long", year: "numeric" });
}

/* Stejná přísná metrika jako src/App.jsx i scripts/og-image.js. Kdyby se
   rozešly, tvrdí každá stránka jiné číslo o téže vládě. */
function metriky(items, evals) {
  let done = 0, partial = 0, prog = 0, broken = 0, n = 0, unver = 0;
  for (const it of items) {
    const v = evals[it.id];
    if (!v || !SCORED.has(v.status)) continue;
    if (v.unverifiable) { unver++; continue; }
    n++;
    if (v.status === "fulfilled") done++;
    else if (v.status === "partial") partial++;
    else if (v.status === "in_progress") prog++;
    else if (v.status === "broken" || v.status === "stalled") broken++;
  }
  const p = (x) => (n ? (x / n) * 100 : 0);
  const one = (v) => (v >= 10 || v === 0 ? Math.round(v) : Math.round(v * 10) / 10);
  return { done: one(p(done)), partial: one(p(partial)), prog: one(p(prog)), broken: one(p(broken)), n, unver };
}

