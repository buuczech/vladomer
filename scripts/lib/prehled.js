export function renderPrehled(lang, { chapters, evals, lastUpdated, totalItems }) {
  const t = T[lang];
  const items = chapters.flatMap((c) => c.groups.flatMap((g) => g.items));
  const m = metriky(items, evals);
  const kdy = datum(lastUpdated, lang);

  /* Česky desetinná čárka a úzká mezera před procentem, anglicky tečka a bez
     mezery. Bez tohohle stálo na anglické stránce „3,5 %“. */
  const procento = (v) => (lang === "cs"
    ? `${String(v).replace(".", ",")}&#8239;%`
    : `${v}%`);

  const cisla = [
    [t.splneno, m.done, BARVY.fulfilled],
    [t.castecne, m.partial, BARVY.partial],
    [t.probiha, m.prog, BARVY.in_progress],
    [t.poruseno, m.broken, BARVY.broken],
  ].map(([k, v, c]) =>
    `<div><dt>${esc(k)}</dt><dd style="color:${c}">${procento(v)}</dd></div>`
  ).join("");

  const telo = chapters.map((ch) => {
    const skupiny = ch.groups.map((g) => {
      const body = g.items.map((it) => {
        const e = evals[it.id];
        const stav = e && t.stavy[e.status] ? t.stavy[e.status] : t.nehodnoceno;
        const barva = (e && BARVY[e.status]) || "#6B7280";
        const komentar = e && e.comment && e.comment[lang] ? e.comment[lang] : "";
        const doklad = e && e.evidence ? e.evidence : "";
        const snizeno = e && t.snizenoProc[e.evidenceMissing] ? e.evidenceMissing : "";
        const zdroje = (e && Array.isArray(e.sources) ? e.sources : [])
          .filter((s) => s && s.url)
          .map((s) => `<li><a href="${esc(s.url)}">${esc(s.title || s.url)}</a></li>`)
          .join("");
        return `<li class="item">
<div class="hd"><span class="title">${esc(it[lang])}</span>`
          + `<span class="badge" style="background:${barva}">${esc(stav)}</span>`
          + `<span class="id">#${esc(it.id)}</span></div>`
          + (e && e.unverifiable ? `<p class="ev">(${esc(t.nemeritelne)})</p>` : "")
          // Před komentářem, ne za ním: rámuje ho, aby čtenář nenarazil nejdřív
          // na tvrzení modelu o splnění a až potom zjistil, že neobstálo.
          + (snizeno ? `<p class="dg"><strong>${esc(t.snizeno)}:</strong> ${esc(t.snizenoProc[snizeno])}</p>` : "")
          + (komentar ? `<p class="cmt">${esc(komentar)}</p>` : "")
          + (doklad ? `<p class="ev"><strong>${esc(t.doklad)}:</strong> ${esc(doklad)}</p>` : "")
          + (zdroje ? `<ul class="src">${zdroje}</ul>` : "")
          + `</li>`;
      }).join("\n");
      const nadpis = g.title && g.title[lang] ? `<h3>${esc(g.title[lang])}</h3>` : "";
      return `${nadpis}<ol class="items">${body}</ol>`;
    }).join("\n");
    return `<section><h2>${esc(ch.id)}. ${esc(ch.title[lang])}</h2>\n${skupiny}</section>`;
  }).join("\n");

  return `<!doctype html>
<html lang="${t.lang}">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>${esc(t.titulek)}</title>
<meta name="description" content="${esc(t.popis)}" />
<link rel="canonical" href="${ORIGIN}/${t.cesta}/" />
<link rel="alternate" hreflang="cs" href="${ORIGIN}/prehled/" />
<link rel="alternate" hreflang="en" href="${ORIGIN}/overview/" />
<link rel="alternate" hreflang="x-default" href="${ORIGIN}/prehled/" />
<link rel="icon" href="../favicon.svg" type="image/svg+xml" />
<style>${CSS}</style>
</head>
<body>
<div class="wrap">
<main>
<h1>${esc(t.h1)}</h1>
<p class="lede">${esc(t.uvod)}</p>
<nav class="nav">
  <a href="../">${esc(t.zpet)}</a>
  <a href="../${t.druha}/" hreflang="${lang === "cs" ? "en" : "cs"}">${esc(t.druhyJazyk)}</a>
  <a href="../evaluations.json">${esc(t.dataText)}</a>
</nav>

<h2 style="border-top:0;padding-top:0;margin-top:0">${esc(t.souhrn)}</h2>
<div class="sum">
<dl>${cisla}</dl>
<p class="caveat">${esc(t.vyhrada)} `
    + (kdy ? `${esc(t.stavK)} <time datetime="${esc(String(lastUpdated).slice(0, 10))}">${esc(kdy)}</time>. ` : `${esc(t.neproběhlo)} `)
    + `${esc(t.hodnocenoZ(m.n, totalItems))}${m.unver ? `, ${m.unver} ${esc(t.nemeritelne)}` : ""}.</p>
</div>
<p class="note">${esc(t.metodikaText)}</p>

${telo}
</main>
<footer>
<p>${esc(t.zdrojProgramu)} · <a href="https://vlada.gov.cz/cz/vlada/programove-prohlaseni/programove-prohlaseni-vlady-224629/">vlada.gov.cz</a></p>
<p>${esc(t.licence)} <a href="https://creativecommons.org/licenses/by/4.0/deed.cs" rel="license">CC BY 4.0</a>.
${esc(t.citace(kdy))}</p>
<p><a href="../">vladomer.cz</a></p>
</footer>
</div>
</body>
</html>
`;
}

